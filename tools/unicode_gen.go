//go:build ignore

// Generates src/unicode_data.zig: the Unicode tables natural-language
// parsing needs, taken from Go's own unicode package so that lowercasing
// and word boundaries match the Go dateparsa exactly.
//
//	zig build unicode    (runs: go run tools/unicode_gen.go src/unicode_data.zig)
//
// Every code point is asked, not the package's internal tables read, so the
// output is right by construction; the Zig side's lookups are checked
// against a dump of the same answers.
package main

import (
	"bytes"
	"fmt"
	"os"
	"runtime"
	"unicode"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run tools/unicode_gen.go <output.zig>")
		os.Exit(2)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Generated by tools/unicode_gen.go from %s's unicode package\n", runtime.Version())
	fmt.Fprintf(&b, "// (Unicode %s). Do not edit; regenerate with `zig build unicode`.\n\n", unicode.Version)
	fmt.Fprintf(&b, "pub const unicode_version = %q;\n\n", unicode.Version)

	b.WriteString("/// Code points lo, lo+stride, ..., hi.\n")
	b.WriteString("pub const Range = struct { lo: u21, hi: u21, stride: u21 };\n\n")
	b.WriteString("/// Each code point in the range lowercases to itself plus delta.\n")
	b.WriteString("pub const LowerRange = struct { lo: u21, hi: u21, stride: u21, delta: i32 };\n\n")

	writeRanges(&b, "letter", "unicode.IsLetter", unicode.IsLetter)
	writeRanges(&b, "digit", "unicode.IsDigit", unicode.IsDigit)
	writeLower(&b)

	if err := os.WriteFile(os.Args[1], b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// writeRanges emits the code points pred accepts as strided ranges: a run
// extends while the gap to the next member stays the same.
func writeRanges(b *bytes.Buffer, name, doc string, pred func(rune) bool) {
	var members []rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if pred(r) {
			members = append(members, r)
		}
	}
	type run struct{ lo, hi, stride rune }
	var runs []run
	for i := 0; i < len(members); {
		lo, stride, j := members[i], rune(1), i+1
		if j < len(members) {
			stride = members[j] - lo
		}
		for j < len(members) && members[j]-members[j-1] == stride {
			j++
		}
		// A single member stands alone rather than claiming a stride the
		// next member would then have to match.
		if j == i+1 {
			stride = 1
		}
		runs = append(runs, run{lo, members[j-1], stride})
		i = j
	}
	fmt.Fprintf(b, "/// The code points %s accepts, sorted.\n", doc)
	fmt.Fprintf(b, "pub const %s = [_]Range{\n", name)
	for _, r := range runs {
		fmt.Fprintf(b, "    .{ .lo = 0x%X, .hi = 0x%X, .stride = %d },\n", r.lo, r.hi, r.stride)
	}
	b.WriteString("};\n\n")
}

// writeLower emits every code point unicode.ToLower changes, as strided
// ranges sharing one delta.
func writeLower(b *bytes.Buffer) {
	type pt struct {
		r     rune
		delta int32
	}
	var pts []pt
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if l := unicode.ToLower(r); l != r {
			pts = append(pts, pt{r, int32(l - r)})
		}
	}
	type run struct {
		lo, hi, stride rune
		delta          int32
	}
	var runs []run
	for i := 0; i < len(pts); {
		p, stride, j := pts[i], rune(1), i+1
		if j < len(pts) && pts[j].delta == p.delta {
			stride = pts[j].r - p.r
		}
		for j < len(pts) && pts[j].delta == p.delta && pts[j].r-pts[j-1].r == stride {
			j++
		}
		if j == i+1 {
			stride = 1
		}
		runs = append(runs, run{p.r, pts[j-1].r, stride, p.delta})
		i = j
	}
	b.WriteString("/// The code points unicode.ToLower changes, sorted.\n")
	b.WriteString("pub const lower = [_]LowerRange{\n")
	for _, r := range runs {
		fmt.Fprintf(b, "    .{ .lo = 0x%X, .hi = 0x%X, .stride = %d, .delta = %d },\n", r.lo, r.hi, r.stride, r.delta)
	}
	b.WriteString("};\n")
}
